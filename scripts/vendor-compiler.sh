#!/usr/bin/env sh
# Rebuild public/atto_compiler.wasm from a clean atto-source.rs checkout and
# write public/atto_compiler.receipt.json. The playground never builds the
# compiler in CI (atto-source.rs is private); CI verifies the receipt digest.
#
# usage: scripts/vendor-compiler.sh /path/to/atto-source.rs
set -eu
src="${1:?usage: vendor-compiler.sh /path/to/atto-source.rs}"
here="$(cd "$(dirname "$0")/.." && pwd)"
cd "$src"
test -z "$(git status --porcelain)" || { echo "atto-source.rs checkout is dirty" >&2; exit 1; }
cargo rustc --locked --release --lib --target wasm32-unknown-unknown --crate-type cdylib -- -C link-arg=--max-memory=67108864
# Never disturb the previously pinned public binary until ALL source-owned
# CI metadata and byte-for-byte artifact reproducibility checks pass.
stage="$(mktemp -d "$here/.atto-vendor.XXXXXX")"
trap 'rm -rf "$stage"' EXIT HUP INT TERM
cp target/wasm32-unknown-unknown/release/atto_compiler.wasm "$stage/atto_compiler.wasm"
head="$(git rev-parse HEAD)"; tree="$(git rev-parse 'HEAD^{tree}')"; rustc="$(rustc --version)"
cd "$here"
STAGE="$stage" HEAD_SHA="$head" TREE_SHA="$tree" RUSTC="$rustc" node --input-type=module <<'JS'
import fs from 'node:fs';
import crypto from 'node:crypto';
const path = (name) => process.env.STAGE + '/' + name;
const bytes = fs.readFileSync(path('atto_compiler.wasm'));
const module = new WebAssembly.Module(bytes);
const { exports: api } = new WebAssembly.Instance(module, {});
const actorSupported = WebAssembly.Module.exports(module).some(x => x.name === 'compile_actor' && x.kind === 'function');
const compilerSha = crypto.createHash('sha256').update(bytes).digest('hex');
// CI metadata must come from a separately reviewed SOURCE-OWNED build,
// not from guesses or an unverified local build. A local rebuild is admissible
// only if its bytes match the approved CI artifact's exact digest.
const actorEvidence = actorSupported ? {
  actor_abi: 'atto.browser.actor.scalar.v0',
  source_ci_run_id: process.env.ATTO_ACTOR_CI_RUN_ID,
  source_ci_job_id: process.env.ATTO_ACTOR_CI_JOB_ID,
  source_ci_artifact_id: process.env.ATTO_ACTOR_CI_ARTIFACT_ID,
  source_ci_compiler_sha256: process.env.ATTO_ACTOR_CI_SHA256,
} : {};
if (actorSupported && (
    ['source_ci_run_id','source_ci_job_id','source_ci_artifact_id']
      .some(key => !/^[1-9][0-9]{0,18}$/.test(actorEvidence[key] ?? '')) ||
    actorEvidence.source_ci_compiler_sha256 !== compilerSha)) {
  throw new Error('E_ACTOR_RELEASE: independently reviewed exact CI run/job/artifact and matching SHA-256 are required');
}
// A developer invoking the vendor script is otherwise one command away from
// writing a private-source compiler binary into a public repository branch.
// Require explicit operator-supplied publication approval values BEFORE
// staging the final public files. These environment values are NOT themselves
// independently authenticated: protected GitHub environment approval and
// independent review remain mandatory before any public PR or deployment.
if (actorSupported) {
  const approvalFields = [
    ['ATTO_PUBLIC_COMPILER_SHA256',compilerSha],
    ['ATTO_PUBLIC_ACTOR_SOURCE_HEAD',process.env.HEAD_SHA],
    ['ATTO_PUBLIC_ACTOR_SOURCE_TREE',process.env.TREE_SHA],
    ['ATTO_PUBLIC_ACTOR_CI_RUN_ID',actorEvidence.source_ci_run_id],
    ['ATTO_PUBLIC_ACTOR_CI_JOB_ID',actorEvidence.source_ci_job_id],
    ['ATTO_PUBLIC_ACTOR_CI_ARTIFACT_ID',actorEvidence.source_ci_artifact_id],
  ];
  for (const [key,expected] of approvalFields) {
    if (!expected || process.env[key] !== expected) {
      throw new Error('E_ACTOR_DISCLOSURE: missing/mismatched explicit local approval for ' + key);
    }
  }
}
const receipt = {
  schema: 'atto.browser.compiler.vendor.v1',
  source_repository: 'atto-lang/atto-source.rs',
  source_head: process.env.HEAD_SHA,
  source_tree: process.env.TREE_SHA,
  toolchain: process.env.RUSTC,
  target: 'wasm32-unknown-unknown',
  compiler_abi: api.abi_version(),
  guest_abi: 'atto.browser.guest.v1',
  ...actorEvidence,
  compiler_sha256: compilerSha,
  compiler_bytes: bytes.length,
};
fs.writeFileSync(path('atto_compiler.receipt.json'), JSON.stringify(receipt, null, 2) + '\n');
fs.writeFileSync(path('compiler-pin.js'),
  '// Generated by scripts/vendor-compiler.sh. The compiler worker refuses any\n' +
  '// compiler whose bytes do not match; tests check this against the receipt.\n' +
  `export const COMPILER_SHA256 = '${receipt.compiler_sha256}';\n` +
  `export const COMPILER_BYTES = ${receipt.compiler_bytes};\n`);
console.log(receipt);
JS
# Promote only a complete, prevalidated set of artifacts. Any partial write
# still fails the independent digest/receipt checks in package-pages.mjs.
cp "$stage/atto_compiler.wasm" "$here/public/atto_compiler.wasm"
cp "$stage/atto_compiler.receipt.json" "$here/public/atto_compiler.receipt.json"
cp "$stage/compiler-pin.js" "$here/src/compiler-pin.js"
